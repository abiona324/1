country_layer = folium.FeatureGroup(name="Country Relationships")

def style_function(feature):
    """Apply styling based on relationship status"""
    fill_color = feature["properties"]["color"]
    fill_opacity_value = 0.7  # Semi-transparent fill by default

    if feature["properties"]["status"] == "Neutral":
        fill_color = "#D1D5DB"  # Light Grey for neutral fill
        fill_opacity_value = 0.9  # Visible but low emphasis

    return {
        "fillColor": fill_color,
        "color": None,  # No outline
        "weight": 0,  # No weight since no outline
        "fillOpacity": fill_opacity_value
    }

def highlight_function(feature):
    """Apply solid fill on hover"""
    fill_color = feature["properties"]["color"]
    fill_opacity_value = 1
    return {
        "fillColor": fill_color,
        "color": None,
        "weight": 0,
        "fillOpacity": fill_opacity_value
    }

tooltip = folium.GeoJsonTooltip(
    fields=["name", "status", "context"],
    aliases=["Country", "Relationship", "Security / Policy Anchors"]
)

