def parse_markdown_table(table_string):
    """Parse markdown table into list of dictionaries"""
    lines = table_string.strip().split('\n')
    if len(lines) < 3:
        return []

    headers = [h.strip() for h in lines[0].strip('|').split('|')]
    data_rows = lines[2:]  # Skip header and separator line

    parsed_data = []
    for row in data_rows:
        if not row.strip():  # Skip empty rows
            continue
        values = [v.strip() for v in row.strip('|').split('|')]
        if len(values) == len(headers):
            parsed_data.append(dict(zip(headers, values)))
    return parsed_data

user_data_list = parse_markdown_table(user_data_markdown)
