    mapped_name = country_name_map.get(country_name, country_name)
    new_status = item["UK Security Relationship"]
    new_color = relationship_to_color_map.get(new_status, "#D1D5DB")

    current_entry = original_uk_relations_detailed.get(mapped_name)
    if current_entry and current_entry[0] == new_status:
        # If country exists in original detailed relations and status is the same, keep original context
        new_context = current_entry[1]
    else:
        # New country, or relationship changed, use default context
        new_context = default_context

    uk_relations[mapped_name] = (new_status, new_context, new_color)

